/**
 * [INPUT]: Deterministic synthetic Ed25519/X25519 seeds.
 * [OUTPUT]: Signed initial workspace proofs for hosted pgTAP; --check verifies committed bytes.
 * [POS]: Test fixture generator. No real credential or signing oracle enters SQL.
 * [PROTOCOL]: Update this header when making changes, then check README.md.
 */
import assert from 'node:assert/strict'
import { readFile, writeFile } from 'node:fs/promises'
import { ed25519, x25519 } from '@noble/curves/ed25519.js'
import { sha256 } from '@noble/hashes/sha2.js'
const hex = bytes => Buffer.from(bytes).toString('hex')
const canonical = value => value && typeof value === 'object' ? Array.isArray(value) ? `[${value.map(canonical).join(',')}]`
  : `{${Object.keys(value).sort().map(key => `${JSON.stringify(key)}:${canonical(value[key])}`).join(',')}}` : JSON.stringify(value)
const sign = (prefix, body, seed) => hex(ed25519.sign(sha256(new TextEncoder().encode(prefix + canonical(body))), seed))
const deviceSeed = new Uint8Array(32).fill(0x42), recoverySeed = new Uint8Array(32).fill(0x24)
const deviceId = '93333333-3333-4333-8333-333333333333'
const signPub = hex(ed25519.getPublicKey(deviceSeed)), boxPub = hex(x25519.getPublicKey(deviceSeed))
const recoverySignPub = hex(ed25519.getPublicKey(recoverySeed)), recoveryBoxPub = hex(x25519.getPublicKey(recoverySeed))
const lines = ['-- Copyright (C) 2026 Jimmy Wong', '-- SPDX-License-Identifier: AGPL-3.0-only', '-- Generated by scripts/gen-sync-security-fixtures.mjs. Synthetic public proofs only.',
  '-- [PROTOCOL]: Update this header when making changes, then check README.md.', 'create temporary table security_proofs(name text primary key, proof jsonb);']
for (let index = 1; index <= 3; index++) {
  const workspaceId = `94444444-4444-4444-8444-44444444444${index}`, generation = `95555555-5555-4555-8555-55555555555${index}`
  const roster = { workspaceId, version: 1, epoch: 1, prevHash: null, devices: [{ id: deviceId, signPub, boxPub }], recoverySignPub, recoveryBoxPub }
  const rosterHash = hex(sha256(new TextEncoder().encode(canonical(roster))))
  const checkpoint = { workspaceId, cpVersion: 1, rosterVersion: 1, rosterHash, epoch: 1, recoverySignPub, recoveryBoxPub, prevCpHash: null }
  const proof = { deviceId, workspaceId, generation, signPub, boxPub, roster, rosterHash, checkpoint,
    rosterSig: sign('goalloom/roster/v1|', roster, deviceSeed), recSig: sign('goalloom/recovery-cp/v1|', checkpoint, recoverySeed), devSig: sign('goalloom/recovery-cp/v1|', checkpoint, deviceSeed) }
  lines.push(`insert into security_proofs values ('workspace${index}', '${JSON.stringify(proof)}'::jsonb);`)
}
const output = lines.join('\n') + '\n', path = new URL('../supabase/tests/sync-security-fixtures.sql', import.meta.url)
if (process.argv.includes('--check')) assert.equal(await readFile(path, 'utf8'), output)
else await writeFile(path, output)
console.log('Synthetic recovery proof fixtures verified')
