import { randomUUID } from 'node:crypto'
import { expect, it } from 'vitest'
import { openDatabase } from '../../src/main/storage/database'
import { migrate, schemaVersion, userVersion, v8Ddl } from '../../src/main/storage/schema'

it('upgrades a v8 file in place and opens a fresh database as v9', () => {
  const legacy = openDatabase(':memory:')
  legacy.exec(v8Ddl)
  const generation = randomUUID()
  const itemId = randomUUID()
  const operationId = randomUUID()
  legacy.prepare('INSERT INTO workspace (id, generation) VALUES (1, ?)').run(generation)
  legacy.prepare(`INSERT INTO items (id,title,description,dueDate,status,completedAt,cancelledAt,archivedAt,deletedAt,deletedBy,createdAt,updatedAt,version,flowColor)
    VALUES (?, '旧任务', '', NULL, 'todo', NULL, NULL, NULL, NULL, NULL, '2026-09-01T00:00:00.000Z', '2026-09-01T00:00:00.000Z', 1, NULL)`).run(itemId)
  legacy.prepare(`INSERT INTO item_placements (itemId,horizon,periodId,sortKey,version,holdPeriodId) VALUES (?, 'later', NULL, 0, 1, NULL)`).run(itemId)
  legacy.prepare(`INSERT INTO operations (id,generation,requestHash,kind,source,at,effectsVersion,effects,result) VALUES (?,?,?,?,?,?,?,?,?)`)
    .run(operationId, generation, 'ab'.repeat(32), 'create', 'user', '2026-09-01T00:00:00.000Z', 1, '[]', '{}')
  legacy.prepare('INSERT INTO item_guidance (itemId,revision,value,updatedAt,operationId) VALUES (?, 1, NULL, ?, ?)').run(itemId, '2026-09-01T00:00:00.000Z', operationId)
  legacy.prepare(`INSERT INTO item_events (id,operationId,eventIndex,itemId,at,type,beforeState,afterState,fromPeriodId,toPeriodId,undoOf)
    VALUES (?, ?, 0, ?, '2026-09-01T00:00:00.000Z', 'created', NULL, '{}', NULL, NULL, NULL)`).run(randomUUID(), operationId, itemId)
  legacy.exec('PRAGMA user_version = 8')
  const before = legacy.prepare('SELECT id, title, version FROM items').all()
  migrate(legacy)
  expect(userVersion(legacy)).toBe(schemaVersion)
  expect(legacy.prepare('SELECT id, title, version FROM items').all()).toEqual(before)
  expect(legacy.prepare('PRAGMA integrity_check').all()).toEqual([{ integrity_check: 'ok' }])
  expect(legacy.prepare('PRAGMA foreign_key_check').all()).toEqual([])
  expect(legacy.prepare("SELECT sql FROM sqlite_master WHERE name='item_events'").get()!.sql).not.toContain('REFERENCES items')
  expect(legacy.prepare("SELECT sql FROM sqlite_master WHERE name='item_guidance'").get()!.sql).not.toContain('REFERENCES operations')
  legacy.prepare('DELETE FROM item_placements WHERE itemId=?').run(itemId)
  legacy.prepare('DELETE FROM item_guidance WHERE itemId=?').run(itemId)
  legacy.prepare('DELETE FROM items WHERE id=?').run(itemId)
  expect(legacy.prepare('SELECT count(*) AS n FROM item_events').get()!.n).toBe(1)
  expect(legacy.prepare('PRAGMA foreign_key_check').all()).toEqual([])
  const opId = randomUUID()
  legacy.prepare(`INSERT INTO sync_ops (opId,localOrder,origin,formatVersion,payload,payloadHash,deviceId,at,state,createdAt,updatedAt)
    VALUES (?, 1, 'local', 1, '{}', ?, 'dev', '2026-09-01T00:00:00.000Z', 'send_unknown', '2026-09-01T00:00:00.000Z', '2026-09-01T00:00:00.000Z')`).run(opId, 'cd'.repeat(32))
  expect(() => legacy.prepare(`UPDATE sync_ops SET state='never_sent' WHERE opId=?`).run(opId)).toThrow(/send_state_irreversible/)
  expect(legacy.prepare('SELECT count(*) AS n FROM base_items').get()!.n).toBe(1)
  legacy.close()

  const fresh = openDatabase(':memory:')
  migrate(fresh)
  expect(userVersion(fresh)).toBe(9)
  expect(fresh.prepare("SELECT name FROM sqlite_master WHERE name='base_items'").get()).toBeTruthy()
  expect(fresh.prepare('SELECT count(*) AS n FROM sync_state').get()!.n).toBe(1)
  fresh.close()
})
